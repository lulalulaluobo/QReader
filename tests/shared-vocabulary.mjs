import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({stdin:{contents:"export * from './src/core/reading-vocabulary'; export * from './src/core/vocabulary';",resolveDir:process.cwd()},bundle:true,write:false,format:'esm',platform:'node',plugins:[{name:'obsidian-test',setup(b){b.onResolve({filter:/^obsidian$/},()=>({path:'obsidian',namespace:'fixture'}));b.onLoad({filter:/.*/,namespace:'fixture'},()=>({contents:'export const requestUrl = async () => { throw Error("Unexpected network"); };'}));}}]});
const m=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const files=new Map();let failPath=null;
const fs={queueScope:{},exists:async p=>files.has(p),read:async p=>{if(!files.has(p))throw Error('missing');return files.get(p);},write:async(p,v)=>{files.set(p,v);if(failPath===p){failPath=null;files.set(p,'partial');throw Error('IO');}},remove:async p=>files.delete(p),mkdir:async()=>{}};
const shared='plugin/vocabulary.json';
const result={query:'integrity',translation:'Being whole and not damaged.',phonetic:'ɪnˈteɡrəti',audioUrl:''};
const legacyWord=(count=1)=>({...result,word:'integrity',lookupCount:count,exposureCount:4,noLookupCount:3,seenParagraphs:['p0','p1']});
const favorite={word:'integrity',translation:'完整',quote:'The integrity of the spine.',cfi:'epubcfi(/6/2!/4/2/1:0)',savedAt:'2026-10-16'};
const originalA=JSON.stringify({version:1,words:[legacyWord()],saved:[favorite]});
const originalB=JSON.stringify({version:1,words:[{...legacyWord(2),noLookupCount:1}],saved:[]});
files.set('A/vocabulary.json',originalA);files.set('B/vocabulary.json',originalB);
const sources=[{bookId:'A',path:'A/vocabulary.json'},{bookId:'B',path:'B/vocabulary.json'}];
const open=async(id,path=id+'/vocabulary.json')=>{const store=new m.ReadingVocabularyStore(fs,shared,id,path);await store.load(sources);return store;};
const parallelA=new m.ReadingVocabularyStore(fs,'parallel/vocabulary.json','A','A/vocabulary.json');
const parallelB=new m.ReadingVocabularyStore(fs,'parallel/vocabulary.json','B','B/vocabulary.json');
await Promise.all([parallelA.load(sources),parallelB.load(sources)]);
assert.equal(JSON.parse(files.get('parallel/vocabulary.json')).words[0].lookupCount,3,'simultaneous first migration commits each legacy book once');
assert.notEqual(m.scopeVocabularyParagraph('A','B:p1'),m.scopeVocabularyParagraph('A:B','p1'));
const a=await open('A'),b=await open('B');
let aUpdates=0,bUpdates=0;
const stopA=a.subscribe(()=>aUpdates++),stopB=b.subscribe(()=>bUpdates++);
assert.equal(a.words.length,1);assert.equal(b.words[0].lookupCount,3);
assert.equal(a.words[0].noLookupCount,1,'merge conservatively retains the less familiar state');
assert.equal(a.words[0].exposureCount,8);
assert.deepEqual(a.words[0].seenParagraphs,['p0','p1']);
assert.equal(a.saved.length,1);assert.equal(b.saved.length,0,'source favorites remain local');
assert.equal(files.get('A/vocabulary.json'),originalA);assert.equal(files.get('B/vocabulary.json'),originalB,'migration leaves source files intact');
await Promise.all([open('A'),open('B')]);
assert.equal(JSON.parse(files.get(shared)).words[0].lookupCount,3,'parallel/repeated migration is idempotent');
// A fresh word queried in A appears in B without a lookup there.
await a.lookup({...result,query:'resilience'},'p0',true);
assert.equal(b.words.find(w=>w.word==='resilience').lookupCount,1);assert.ok(aUpdates&&bUpdates);
const exposure=(word,paragraphId,count=1)=>[{word,paragraphId,lookupCount:count}];
await b.expose(exposure('resilience','p0'),5);
assert.equal(a.words.find(w=>w.word==='resilience').noLookupCount,1,'same paragraph ID in another book counts independently');
await b.expose(exposure('resilience','p0'),5);
assert.equal(a.words.find(w=>w.word==='resilience').noLookupCount,1,'same book paragraph is deduplicated');
await a.expose(exposure('resilience','p0'),5);
assert.equal(a.words.find(w=>w.word==='resilience').noLookupCount,1,'lookup paragraph is suppressed in the source book');
await a.expose(exposure('resilience','p1'),5);
assert.equal(b.words.find(w=>w.word==='resilience').noLookupCount,2);
// A lookup in B resets shared familiarity and invalidates pending old exposure events.
await b.lookup({...result,query:'resilience'},'p1',true);
await a.expose(exposure('resilience','pending-old',1),5);
assert.equal(a.words.find(w=>w.word==='resilience').noLookupCount,0);
assert.equal(a.words.find(w=>w.word==='resilience').lookupCount,2);
await a.expose(exposure('resilience','p1',2),5);
await b.expose(exposure('resilience','p0',2),5);
assert.equal(a.words.find(w=>w.word==='resilience').noLookupCount,2);
for(let i=0;i<3;i++)await b.expose(exposure('resilience','new'+i,2),5);
assert.ok(!a.words.some(w=>w.word==='resilience')&&!b.words.some(w=>w.word==='resilience'),'shared threshold removes highlights from both books');
await a.remove('integrity');
assert.equal(b.words.length,0);assert.equal(a.saved.length,1);
await open('A');await open('B');
assert.equal(JSON.parse(files.get(shared)).words.length,0,'legacy files cannot resurrect removed or mastered words');
await b.keep({...favorite,quote:'A different sentence in book B.'});
assert.equal(a.saved.length,1);assert.equal(b.saved.length,1);assert.equal(a.saved[0].quote,favorite.quote);
await b.unkeep(b.saved[0]);assert.equal(b.saved.length,0);assert.equal(a.saved.length,1);
// New books inherit existing words, independent of their own vocabulary.json file.
await a.lookup(result,'p2',true);
const c=await open('C');assert.equal(c.words[0].word,'integrity');assert.equal(c.saved.length,0);
assert.equal(files.has('C/vocabulary.json'),false,'reading does not create an unnecessary per-book word list');
const before=files.get(shared);failPath=shared;
await assert.rejects(b.lookup({...result,query:'failure'},'p1',true),/IO/);
assert.equal(files.get(shared),before);assert.ok(!b.words.some(w=>w.word==='failure'),'failed shared writes roll back');
// Invalid legacy records stop migration without changing the shared file.
files.set('bad/vocabulary.json','broken');
await assert.rejects(new m.ReadingVocabularyStore(fs,shared,'bad','bad/vocabulary.json').load([{bookId:'bad',path:'bad/vocabulary.json'}]),/无效/);
assert.equal(files.get(shared),before);
// A failed migration commits neither words nor the idempotence marker and can be retried.
files.set('D/vocabulary.json',JSON.stringify({version:1,words:[{...legacyWord(),word:'effort',query:'effort'}]}));
const d=new m.ReadingVocabularyStore(fs,shared,'D','D/vocabulary.json');
failPath=shared;await assert.rejects(d.load([{bookId:'D',path:'D/vocabulary.json'}]),/IO/);
assert.equal(files.get(shared),before);
await d.load([{bookId:'D',path:'D/vocabulary.json'}]);assert.ok(d.words.some(w=>w.word==='effort'));
const afterMigration=files.get(shared);await d.load([{bookId:'D',path:'D/vocabulary.json'}]);assert.equal(files.get(shared),afterMigration);
stopA();stopB();
console.log('Shared vocabulary: cross-book propagation/familiarity/reset/threshold/removal, book-local favorites, scoped paragraphs, atomic/idempotent legacy migration, rollback and corruption guards passed.');
