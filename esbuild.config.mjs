import esbuild from "esbuild";
import fs from "fs";
import process from "process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
QReader — Read with Questions
*/
`;

const prod = process.argv[2] === "production";

// Keep the worker and all PDF decoding resources inside main.js.
const pdfAssetsPlugin = {
  name: "offline-pdf-assets",
  setup(build) {
    build.onLoad({ filter: /pdf\.worker(\.min)?\.mjs$/ }, async (args) => ({
      contents: `export default ${JSON.stringify(await fs.promises.readFile(args.path, "utf8"))};`,
      loader: "js",
    }));
    build.onResolve({ filter: /^qreader:pdf-assets$/ }, () => ({
      path: "pdf-assets",
      namespace: "qreader",
    }));
    build.onLoad({ filter: /.*/, namespace: "qreader" }, async () => {
      const assets = {};
      for (const dir of ["standard_fonts", "cmaps", "wasm"]) {
        const root = `node_modules/pdfjs-dist/${dir}`;
        for (const file of await fs.promises.readdir(root)) {
          if (!/\.(pfb|ttf|bcmap|wasm)$/.test(file)) continue;
          assets[`${dir}/${file}`] = (await fs.promises.readFile(`${root}/${file}`)).toString("base64");
        }
      }
      return { contents: `export default ${JSON.stringify(assets)};`, loader: "js" };
    });
  },
};

// Foliate 1.0.1 的 FB2 样式在模块初始化时创建无法由 book.destroy() 释放的
// blob URL。静态 CSS 改用 data URL；图像等书籍资源仍由 Foliate 释放。
const foliateStylesPlugin = {
  name: "foliate-static-fb2-style",
  setup(build) {
    build.onLoad({ filter: /foliate-js\/fb2\.js$/ }, async (args) => {
      const source = await fs.promises.readFile(args.path, "utf8");
      const allocation = /const style = URL\.createObjectURL\(new Blob\(\[(`[\s\S]*?`)\], \{ type: 'text\/css' \}\)\)/g;
      if ([...source.matchAll(allocation)].length !== 1) {
        throw new Error("Foliate FB2 样式结构已改变，请检查静态资源适配");
      }
      return {
        contents: source.replace(allocation, "const style = 'data:text/css;charset=utf-8,' + encodeURIComponent($1)"),
        loader: "js",
      };
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  platform: "browser",
  alias: {
    "jszip": "jszip/lib/index.js",
    "jszip/dist/jszip": "jszip/lib/index.js",
    stream: "stream-browserify",
    buffer: "buffer/",
  },
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  outfile: "main.js",
  sourcemap: prod ? false : "inline",
  minify: prod,
  loader: { ".pfb": "base64", ".ttf": "base64" },
  plugins: [pdfAssetsPlugin, foliateStylesPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
